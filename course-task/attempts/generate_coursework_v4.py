def set_font(run, size=14, bold=False, italic=False):
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')

def add_para(doc, text, size=14, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    run = p.add_run(text)
    set_font(run, size, bold)
    return p

def add_heading(doc, text, level=1, align=None):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    elif level == 1:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(12) if level == 1 else Pt(6)
    run = p.add_run(text)
    set_font(run, 14, bold=True)
    return p

def set_cell(cell, text, bold=False, align=WD_ALIGN_PARAGRAPH.CENTER, size=12):
    cell.text = ""
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.space_before = Pt(2)
    run = p.add_run(text)
    set_font(run, size, bold)

