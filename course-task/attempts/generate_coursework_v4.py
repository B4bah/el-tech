def closest_value(value, series):
    """Выбор ближайшего стандартного номинала из ряда"""
    if value <= 0:
        return series[0]
    exp = math.floor(math.log10(value))
    base = value / (10**exp)
    closest = min(series, key=lambda x: abs(x - base))
    return closest * (10**exp)

def fmt_res(val):
    """Форматирование сопротивления"""
    if val >= 1e6:
        return f"{val/1e6:g} МОм"
    if val >= 1e3:
        return f"{val/1e3:g} кОм"
    return f"{val:g} Ом"

def fmt_cap(val):
    """Форматирование ёмкости"""
    if val >= 1e-3:
        return f"{val*1e3:g} мкФ"
    if val >= 1e-6:
        return f"{val*1e6:g} нФ"
    if val >= 1e-9:
        return f"{val*1e9:g} пФ"
    return f"{val:g} Ф"

